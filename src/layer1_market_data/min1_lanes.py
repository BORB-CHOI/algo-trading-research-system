"""1분봉을 **어느 시장은 어느 창구에서 받나** — 표 하나로 정한다.

## 원칙: 한 시장은 통째로 한 창구가 맡는다

종목마다 창구를 갈라 두 곳을 동시에 돌리면 제일 빠르다(6.6분). 그런데 두 창구는 봉
하나까지 같지 않아서(아래 "두 창구 값이 얼마나 같나"), **종목 A 와 종목 B 가 서로 다른
규칙으로 만들어진다.** 조건검색은 전 종목을 같은 잣대로 훑는 일이라 그러면 안 된다.
지표도 마찬가지다 — 이동평균·RSI 는 앞 봉 N 개를 보는데, 종목마다 봉을 나누는 자리가
다르면 잣대가 종목마다 달라진다.

오너 결정 2026-08-30: **정확도는 타협 불가. 속도를 종목 섞기로 사지 않는다.**
한도를 제대로 쓰고 나니 섞어서 얻을 것도 얼마 없다 — 9.5분이 6.6분 되는 게 전부다.

## 창구별 실측 (2026-08-30, 재시도까지 넣어 **실제로 지나간 콜**로 잼)

    나무   초당 4.25   SDK 가 5 에서 더 못 올리게 막는다
    키움   초당 9.68   429 는 다시 부르면 그냥 지나간다 (못 받은 콜 0)
    KIS    초당 16     그런데 **한 콜에 120줄뿐** — KRX 하루 381분에 5콜이 든다

보관도 재봤다. 1분봉 기준:

    나무   39 거래일
    키움   262 거래일 (2025-08-01~)   ← 굵기 1~240분 전부 같은 깊이
    KIS    2025-09 언저리부터          ← 키움보다 짧다. "과거만 KIS" 는 얻을 게 없다

## 왜 키움인가 — 빠른 것보다 **나무가 날을 통째로 잃는다**는 게 크다

나무 1분봉을 전 종목으로 훑어 보니 **특정 날이 통째로 비어 있다**(호출 0, 2026-08-30):

    KRX  2026-07-07  3,499/3,499 종목 잘림 (100%)
         2026-07-28  3,516/3,516 종목 잘림 (100%)
    통합 2026-07-13 · 07-24 · 08-05  각 99.8%  ·  08-19  38.7%

39 거래일 중 KRX 2일·통합 4일이다. 그 날 키움엔 체결이 멀쩡히 들어 있다.
조용히 비어 있어서 오래 못 봤다 — 굵은 봉을 만들 때 `minute_bars.complete_days` 가
걸러 주고 있었을 뿐이다.

## 통합(unt)도 키움으로 — 다만 시간외 물량은 빠진다

**"통합 = KRX + NXT" 는 대체로 맞는다.** 나무 값끼리, 온전한 날만 놓고 150종목
3,466,839봉을 맞대 봤다:

    봉 하나까지 거래량이 같은 비율   98.72%
    거래량 합의 차   중앙값 0.0024% · 95분위 1.05% · 최대 4.70%

어긋나는 몫은 **KRX 시간외단일가**다. 통합에만 따로 실리고 KRX 1분봉엔 어느 창구든
안 담긴다. 거래가 많을수록 커진다:

    하루 거래대금 아래쪽 절반   0.000%      80~95분위   0.036%
    50~80분위                 0.029%      상위 5%     0.780% (최대 1.73%)

키움 통합은 그 시간외를 안 담는다(= 키움 KRX + 키움 NXT 와 정확히 같다, 0.00000%).
**치를 값은 거래 큰 종목에서 통합 1분봉 거래량이 0.8~1.7% 적어지는 것**이고,
얻는 것은 나무가 잃은 4일과 39일 → 262일이다.

되돌리려면 아래 `BROKER["unt"] = "namuh"` 한 줄이다.

## 두 창구 값이 얼마나 같나 — 봉 하나까지 똑같지는 않다 (실측 2026-08-30)

KRX 58종목 155,210봉을 거래가 활발한 정도로 열 구간을 갈라 봤다:

    하루 체결분   4분(가장 한산)   봉 완전일치 95.4%
                176분(중앙값)                88.3%
                361분(가장 활발)             46.9%

굵은 분봉으로 봐도(005930): 고가·저가는 min3 98.9%·min60 99.6% 로 맞는데 시가·종가가
절반쯤 1호가 다르다. 거래량 합의 차는 min3 0.0108% · min60 0.0119%.

**어느 쪽이 틀린 게 아니라 1분 경계에 걸린 체결을 다른 봉에 넣는 것이다.** 그래서 섞지
않는다 — 한 시장은 통째로 한 창구가 맡는다.

거꾸로 KIS 는 키움과 **같은 규칙**이다(005930 08-28 381봉: 시·고·저·종 100% 일치,
거래량 99.7%). 창구로 쓰기엔 콜당 120줄이라 느리지만, **키움 값이 틀어지는지 보는
대조용으로는 KIS 가 맞다.**
"""

from __future__ import annotations

# ─────────────────────────────────────────────────────────────────────────────
# 표 하나 — 시장마다 어느 창구가 맡나 (오너가 고른다)
# ─────────────────────────────────────────────────────────────────────────────
# 값은 "kiwoom" 아니면 "namuh". 시장을 통째로 옮기는 것이라 종목은 안 섞인다.
#
#   전부 키움 (지금)          9.5분   1분봉 39일 → 262일 · 나무가 잃은 날이 메워진다
#   통합만 나무로 되돌리면     8.5분   통합에 시간외까지 담긴다 · 통합은 39일에 머문다
#   전부 나무                21.6분   지금까지 하던 방식
#
# ⚠️ **바꾸면 그 시장을 한 번 다시 받아야 한다.** 안 그러면 그 시장 파일에 옛 창구 값과
# 새 창구 값이 날짜로 섞인다 → `scripts/backfill_kiwoom_min1.py`
BROKER: dict[str, str] = {
    "krx": "kiwoom",
    "nxt": "kiwoom",
    "unt": "kiwoom",
}

# 실측 한도(초당) — 재시도까지 넣어 **실제로 지나간 콜**로 잰 값 (2026-08-30, 각 90초).
RATE = {
    "namuh": 4.25,   # SDK 상한 5 로 올린 값. 그 이상은 SDK 가 막는다
    "kiwoom": 9.68,  # 목표 12 로 던졌을 때. 429 는 다시 부르면 지나간다(못 받은 콜 0)
}


def broker_of_market(market: str) -> str:
    """이 시장의 1분봉을 어느 창구가 맡나. 모르는 시장이면 나무(지금까지의 창구)."""
    return BROKER.get(str(market).lower(), "namuh")


def split(jobs: list[tuple[str, list[str]]]) -> dict[str, list[tuple[str, list[str]]]]:
    """(종목, 시장들) 목록을 창구별 몫으로 가른다. 시장이 안 남은 종목은 그 몫에서 빠진다."""
    lanes: dict[str, list[tuple[str, list[str]]]] = {"namuh": [], "kiwoom": []}
    for code, markets in jobs:
        keep: dict[str, list[str]] = {"namuh": [], "kiwoom": []}
        for market in markets:
            keep[broker_of_market(market)].append(market)
        for lane, got in keep.items():
            if got:
                lanes[lane].append((code, got))
    return lanes


def estimate_sec(lanes: dict[str, list[tuple[str, list[str]]]]) -> dict[str, float]:
    """각 창구가 몇 초쯤 걸릴지 — 콜 수 ÷ 실측 한도. 로그에 남겨 치우침을 바로 본다."""
    return {
        lane: round(sum(len(ms) for _, ms in jobs) / RATE[lane], 1)
        for lane, jobs in lanes.items()
    }


__all__ = ["BROKER", "RATE", "broker_of_market", "estimate_sec", "split"]
